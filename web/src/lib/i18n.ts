const dict: Record<Lang, Record<string, string>> = { en, ko };
const LS_KEY = 'vibe.lang';

function detect(): Lang {
  try {
    const saved = localStorage.getItem(LS_KEY) as Lang | null;
    if (saved === 'en' || saved === 'ko') return saved;
  } catch { /* ignore */ }
  return typeof navigator !== 'undefined' && navigator.language.toLowerCase().startsWith('ko') ? 'ko' : 'en';
}

let current: Lang = detect();
const listeners = new Set<() => void>();

export function getLang(): Lang { return current; }

/** Switch language app-wide. `fromHost` marks a change pushed by the Electron menu (no echo back). */
export function setLang(l: Lang, fromHost = false) {
  if (l !== 'en' && l !== 'ko') return;
  if (l === current) { if (!fromHost) window.vibe?.setLanguage?.(l); return; }
  current = l;
  try { localStorage.setItem(LS_KEY, l); } catch { /* ignore */ }
  document.documentElement.lang = l;
  if (!fromHost) window.vibe?.setLanguage?.(l);
  for (const f of listeners) f();
}

/** Translate a key; `{name}` placeholders are filled from params. Falls back to English, then the key. */
export function t(key: string, params?: Record<string, string | number>): string {
  const s = dict[current][key] ?? dict.en[key] ?? key;
  return params ? s.replace(/\{(\w+)\}/g, (_, k: string) => String(params[k] ?? '')) : s;
}

/** Subscribe a component to language changes. Call once at the top of any component that renders text. */
export function useLang(): Lang {
  const [, force] = useState(0);
  useEffect(() => {
    const f = () => force((x) => x + 1);
    listeners.add(f);
    return () => { listeners.delete(f); };
  }, []);
  return current;
}

// Wire the Electron menu both ways: menu → page, and page → menu (initial checkmark).
if (typeof window !== 'undefined') {
  document.documentElement.lang = current;
  window.vibe?.onLanguage?.((l) => setLang(l as Lang, true));
  window.vibe?.setLanguage?.(current);
}
