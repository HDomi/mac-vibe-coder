// Build a complete, signed bundle in a staging location before replacing the installed app.
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');

function launcherSource(root) {
  return `// Generated by install.sh.\ntry { require(${JSON.stringify(path.join(root, 'dist/electron/main.cjs'))}); } catch (error) {\n  const { app, dialog } = require('electron');\n  app.whenReady().then(() => { dialog.showErrorBox('Vibrato', 'Could not load the checkout. Run install.sh again.\\n' + error.message); app.quit(); });\n}\n`;
}

if (require.main === module) {
  const [source, target, root] = process.argv.slice(2);
  if (!source || !target || !root) throw new Error('Usage: create-app.cjs source target checkout');
  fs.cpSync(source, target, { recursive: true, errorOnExist: true, force: false, verbatimSymlinks: true });
  const name = 'Vibrato';
  fs.renameSync(path.join(target, 'Contents/MacOS/Electron'), path.join(target, 'Contents/MacOS', name));
  execFileSync('/usr/libexec/PlistBuddy', ['-c', `Set :CFBundleExecutable ${name}`, path.join(target, 'Contents/Info.plist')]);
  const resources = path.join(target, 'Contents/Resources/app');
  fs.mkdirSync(resources, { recursive: true });
  const version = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8')).version;
  fs.writeFileSync(path.join(resources, 'package.json'), JSON.stringify({ name: 'vibrato', productName: name, version, main: 'launcher.js' }));
  fs.writeFileSync(path.join(resources, 'launcher.js'), launcherSource(root));
  execFileSync('codesign', ['--force', '--deep', '--sign', '-', target], { stdio: 'inherit' });
}

module.exports = { launcherSource };
